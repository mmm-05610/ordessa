def test_generation_is_opaque_monotonic_and_old_targets_are_retired(setup):
    registry, service, args = setup
    first = service.bind(**args)
    registry.generation = "000000000000000000000"
    with pytest.raises(ProfileOwnerUnavailable, match="target stale"):
        service.readback(first.target)
    second = service.bind(**args)
    assert second.target.runtime_generation == 2
    queries = registry.queries
    with pytest.raises(ProfileOwnerUnavailable, match="stale"):
        service.readback(first.target)
    assert registry.queries == queries
    registry.generation = "opaque/not-an-int"
    with pytest.raises(ProfileOwnerUnavailable, match="retired native generation"):
        service.bind(**args)
    registry.generation = "-99"
    with pytest.raises(ProfileOwnerUnavailable, match="invalidated"):
        service.bind(**args)
    registry.generation = "000000000000000000000"
    with pytest.raises(ProfileOwnerUnavailable, match="invalidated"):
        service.readback(second.target)


def test_new_opaque_generation_advances_without_numeric_ordering(setup):
    registry, service, args = setup
    first = service.bind(**args)
    registry.generation = "-99"
    second = service.bind(**args)
    assert second.target.runtime_generation == first.target.runtime_generation + 1


@pytest.mark.parametrize("mutate", [
    lambda registry: setattr(registry.channel, "ended", True),
    lambda registry: setattr(registry, "owner", replace(registry.owner, execution_id="replacement")),
    lambda registry: setattr(registry, "owner", replace(registry.owner)),
    lambda registry: setattr(registry.channel, "workspace_id", "replacement"),
])
def test_changed_or_closed_owner_rejects_existing_target_and_silent_rebind(setup, mutate):
    registry, service, args = setup
    first = service.bind(**args)
    mutate(registry)
    with pytest.raises(ProfileOwnerUnavailable):
        service.readback(first.target)
    with pytest.raises(ProfileOwnerUnavailable):
        service.bind(**args)
    assert registry.queries == 1


