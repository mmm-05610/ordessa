def test_busy_change_retires_previous_fence_until_idle_independent_read(setup):
    registry, service, args = setup
    first = service.bind(**args)
    registry.busy = True
    registry.generation = "busy-generation"
    with pytest.raises(ProfileOwnerUnavailable, match="busy"):
        service.readback(first.target)
