@pytest.fixture
def actual_registry_controlled_transport():
    """Actual registry/channel observers; transport and ledger are controlled.

    Direct fixture registration avoids launching a process or asserting durable
    product identity provenance. Native IDs are generated by fixture responses.
    """
    channel = _Channel(connection_id="channel", harness_id="pi", workspace_id="project",
                       profile_id="fixture-profile", cwd="/fixture-project")
    channel.session_id = "fixture-ledger"
    channel.execution_id = "fixture-execution"

    class ControlledTransport:
        next_native_id = "native-a"
        generations = {"native-a": "generation-a", "native-b": "generation-b"}
        sent = None

        def __init__(self):
            self.sent = []

        def send_line(self, line):
            frame = json.loads(line)
            self.sent.append(frame)
            if frame["method"] == "session/new":
                result = {"sessionId": self.next_native_id}
            else:
                assert frame["method"] == "_ordessa/session/configuration"
                native_id = frame["params"]["sessionId"]
                result = {"sessionId": native_id, "generation": self.generations[native_id],
                          "busy": False, "configOptions": [{"id": "thinking", "currentValue": "low"}]}
            channel.deliver(json.dumps({"jsonrpc": "2.0", "id": frame["id"], "result": result}))

    transport = ControlledTransport()
    channel.transport = _ObservedTransport(channel, transport)
    registry = AcpChannelRegistry(session_records=None, profile_records=None,
                                  launch=lambda **kwargs: pytest.fail("fixture must not launch"))
    with registry._lock:
        registry._by_id[channel.connection_id] = channel
        registry._by_pair[channel.pair] = channel

    def create(native_id):
        transport.next_native_id = native_id
        channel.transport.send_line(json.dumps({"jsonrpc": "2.0", "id": f"new-{len(transport.sent)}",
                                               "method": "session/new", "params": {}}))

    return registry, channel, transport, create


def test_real_registry_same_id_new_session_retires_bound_target(actual_registry_controlled_transport):
    registry, channel, transport, create = actual_registry_controlled_transport
    create("native-a")
    original = registry.native_session_observation("channel", "native-a")
    service = ProfileSessionOwner(registry, server_id="fixture-server-incarnation")
    args = dict(canonical_session_id="canonical-a", harness_id="pi", workspace_id="project",
                connection_id="channel", native_session_id="native-a")
    first = service.bind(**args)
    create("native-a")
    replacement = registry.native_session_observation("channel", "native-a")
    assert original == replacement
    assert original is not replacement
    sent = len(transport.sent)
    with pytest.raises(ProfileOwnerUnavailable, match="owner or scope changed"):
        service.readback(first.target)
    with pytest.raises(ProfileOwnerUnavailable):
        service.bind(**args)
    assert len(transport.sent) == sent


def test_real_registry_interleaved_sessions_keep_their_own_current_fence(actual_registry_controlled_transport):
    registry, channel, transport, create = actual_registry_controlled_transport
    create("native-a")
    create("native-b")
    service = ProfileSessionOwner(registry, server_id="fixture-server-incarnation")
    common = dict(harness_id="pi", workspace_id="project", connection_id="channel")
    args_a = dict(common, canonical_session_id="canonical-a", native_session_id="native-a")
    args_b = dict(common, canonical_session_id="canonical-b", native_session_id="native-b")
    a1 = service.bind(**args_a)
    b1 = service.bind(**args_b)
    assert (a1.target.runtime_generation, b1.target.runtime_generation) == (1, 2)
    assert service.readback(a1.target).target == a1.target
    transport.generations["native-a"] = "generation-a-new"
    a2 = service.bind(**args_a)
    assert a2.target.runtime_generation == 3
    assert service.readback(b1.target).target == b1.target
    transport.generations["native-b"] = "generation-b-new"
    b2 = service.bind(**args_b)
    assert b2.target.runtime_generation == 4
    assert service.readback(a2.target).target == a2.target
    with pytest.raises(ProfileOwnerUnavailable, match="stale"):
        service.readback(a1.target)
    with pytest.raises(ProfileOwnerUnavailable, match="stale"):
        service.readback(b1.target)


class ControlledRegistry:
    def __init__(self):
        self.owner = NativeSessionObservation("channel", "execution", "ledger", "native")
        self.channel = SimpleNamespace(harness_id="pi", workspace_id="project", ended=False)
        self.generation = "opaque/not-an-int"
        self.busy = False
        self.queries = 0
        self.after_query = lambda: None
        self.result_owner = None
        self.unavailable = False

    def get(self, connection_id):
        return self.channel if connection_id == "channel" else None

    def native_session_observation(self, connection_id, native_session_id):
        if self.channel.ended:
            return None
        return self.owner if (connection_id, native_session_id) == ("channel", "native") else None

    def query_native_configuration(self, connection_id, native_session_id, *, timeout):
        self.queries += 1
        if self.unavailable:
            raise NativeConfigurationUnavailable("controlled absent readback")
        result = NativeConfigurationObservation(self.result_owner or self.owner, self.generation,
            self.busy, '[{"id":"thinking","currentValue":{"level":"low"}}]')
        self.after_query()
        return result


