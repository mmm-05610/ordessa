"""Explicit OpenShell assembly inputs for a local CLI composition.

The CLI binds a public Environment port; every SDK/gRPC/TLS detail stays here.
Configuration carries data and file *references* only: the mTLS key path is a
path, never key material, and no credential value is read, copied or logged.

Two constraints are enforced here rather than left to callers:

- the endpoint is a gRPC ``host:port`` (a URL scheme makes gRPC resolve a
  hostname that does not exist);
- loopback gRPC never goes through an ambient HTTP proxy. A local gateway is
  reached directly, so proxy variables are removed for this process when the
  endpoint is loopback. They are never consulted for the sandbox itself.

Sandbox names are generated by the provider (19-character bound); this module
does not invent names.
"""
from __future__ import annotations

import json
import os
from dataclasses import dataclass
from pathlib import Path

from openshell._proto import openshell_pb2_grpc
from openshell.sandbox import SandboxClient, TlsConfig
from ordessa_environments import EnvironmentRefused

from .configuration import OpenShellConfiguration
from .provider import OpenShellEnvironmentProvider

_LOOPBACK = frozenset({'127.0.0.1', 'localhost', '::1', '0:0:0:0:0:0:0:1'})
_PROXY_VARIABLES = ('http_proxy', 'https_proxy', 'all_proxy', 'grpc_proxy',
                    'HTTP_PROXY', 'HTTPS_PROXY', 'ALL_PROXY', 'GRPC_PROXY')
#: Gateway registration root written by the official CLI (``openshell gateway add``).
DEFAULT_GATEWAY_ROOT = Path.home() / '.config' / 'openshell' / 'gateways'
_MTLS_FILES = {'ca': 'ca.crt', 'cert': 'tls.crt', 'key': 'tls.key'}


@dataclass(frozen=True)
class OpenShellBinding:
    """One built provider plus the facts its catalog entry may state."""

    provider: OpenShellEnvironmentProvider
    catalog: dict


def _text(value, name, *, maximum=512):
    if type(value) is not str or not value or len(value) > maximum:
        raise EnvironmentRefused('OpenShell configuration requires ' + name)
    return value


def _endpoint_host(endpoint: str) -> str:
    host, _, port = endpoint.rpartition(':')
    if not host or not port.isdigit() or not 0 < int(port) < 65536:
        raise EnvironmentRefused('OpenShell endpoint must be an explicit host:port gRPC address')
    if '://' in endpoint:
        raise EnvironmentRefused('OpenShell endpoint must be host:port without a URL scheme')
    return host.strip('[]')


def _bypass_ambient_proxy(endpoint: str) -> None:
    """Reach a loopback gateway directly; never consult an ambient proxy."""
    if _endpoint_host(endpoint) not in _LOOPBACK:
        return
    for name in _PROXY_VARIABLES:
        os.environ.pop(name, None)


def _mtls_paths(config: dict, gateway_name: str) -> TlsConfig:
    """Explicit certificate paths, else the official gateway registration."""
    explicit = {key: config.get(field) for key, field in
                (('ca', 'caPath'), ('cert', 'certPath'), ('key', 'keyPath'))}
    if any(value is not None for value in explicit.values()):
        if any(value is None for value in explicit.values()):
            raise EnvironmentRefused('OpenShell mTLS requires caPath, certPath and keyPath together')
        paths = {key: Path(value) for key, value in explicit.items()}
    else:
        root = DEFAULT_GATEWAY_ROOT / gateway_name
        if not root.is_dir():
            raise EnvironmentRefused('OpenShell gateway registration or explicit mTLS paths required')
        paths = {key: root / 'mtls' / name for key, name in _MTLS_FILES.items()}
    for key, path in paths.items():
        if not path.is_file():
            raise EnvironmentRefused('OpenShell mTLS ' + key + ' file is absent')
    return TlsConfig(ca_path=paths['ca'], cert_path=paths['cert'], key_path=paths['key'])


def read_configuration(path) -> dict:
    """Read one bounded JSON object; a missing file means OpenShell is unconfigured."""
    try:
        raw = Path(path).read_bytes()
    except FileNotFoundError:
        return {}
    except OSError:
        raise EnvironmentRefused('OpenShell configuration is unreadable') from None
    if len(raw) > 65536:
        raise EnvironmentRefused('OpenShell configuration exceeds its bounded size')
    try:
        value = json.loads(raw)
    except (ValueError, UnicodeDecodeError):
        raise EnvironmentRefused('OpenShell configuration is not JSON') from None
    if not isinstance(value, dict):
        raise EnvironmentRefused('OpenShell configuration must be a JSON object')
    return value


def _validate(config: dict) -> tuple[str, str, str, str | None, str, float]:
    known = {'endpoint', 'workspace', 'fileRoot', 'fileHelper', 'timeoutSeconds',
             'gatewayName', 'caPath', 'certPath', 'keyPath'}
    if set(config) - known:
        raise EnvironmentRefused('OpenShell configuration has unknown fields')
    endpoint = _text(config.get('endpoint', '127.0.0.1:17670'), 'endpoint')
    _endpoint_host(endpoint)
    workspace = _text(config.get('workspace'), 'workspace', maximum=128)
    file_root = _text(config.get('fileRoot', '/sandbox'), 'fileRoot', maximum=1024)
    if not file_root.startswith('/') or os.path.normpath(file_root) != file_root:
        raise EnvironmentRefused('OpenShell fileRoot must be a canonical absolute backend path')
    helper = config.get('fileHelper')
    if helper is not None:
        helper = _text(helper, 'fileHelper', maximum=512)
    gateway_name = _text(config.get('gatewayName', 'openshell'), 'gatewayName', maximum=128)
    timeout = config.get('timeoutSeconds', 60)
    if type(timeout) not in (int, float) or not 0 < timeout <= 600:
        raise EnvironmentRefused('OpenShell timeoutSeconds is out of its bounded range')
    return endpoint, workspace, file_root, helper, gateway_name, float(timeout)


def build_binding(config: dict) -> OpenShellBinding:
    """Build the provider from validated data; raises ``EnvironmentRefused`` on absence."""
    if not config:
        raise EnvironmentRefused('OpenShell is not configured for this state directory')
    endpoint, workspace, file_root, helper, gateway_name, timeout = _validate(config)
    _bypass_ambient_proxy(endpoint)
    tls = _mtls_paths(config, gateway_name)
    client = SandboxClient(endpoint, tls=tls, timeout=timeout)
    try:
        health = client.health()
    except Exception:
        client.close()
        raise EnvironmentRefused('OpenShell gateway is unreachable or unauthenticated') from None
    version = health.version.removeprefix('v')
    configuration = OpenShellConfiguration(
        workspace=workspace, file_root=file_root, gateway_reference=gateway_name,
        file_helper=helper, timeout_seconds=timeout)
    # One authority: the provider speaks over the exact channel the SDK client
    # authenticated with (same TLS identity, same interceptors), instead of
    # opening a second channel that could carry different credentials. The SDK
    # exposes no public channel accessor, so this single private read is kept
    # here in the plugin that owns the SDK contract; the CLI never sees it.
    channel = getattr(client, '_channel', None)
    if channel is None:
        client.close()
        raise EnvironmentRefused('OpenShell SDK channel is unavailable to the provider')
    rpc = openshell_pb2_grpc.OpenShellStub(channel)
    provider = OpenShellEnvironmentProvider(configuration, client=client, rpc=rpc)
    catalog = {
        'id': 'openshell', 'available': True, 'gateway': gateway_name,
        'gatewayVersion': version, 'workspace': workspace,
        'endpointKind': 'openshell-sandbox',
        'isolation': 'openshell-policy',
        'capabilities': ['process', 'byte-channel', 'streaming-stderr',
                         'file-area' if helper is not None else 'file-area-conditional'],
        # The file area is advertised as conditional until a live helper probe
        # runs on an acquired Use; configuration alone is not a probe result.
        'filesRequireHelperProbe': True,
        'perProcessStop': False, 'processReconnect': False,
        'operations': sorted(provider.operations),
    }
    return OpenShellBinding(provider=provider, catalog=catalog)
