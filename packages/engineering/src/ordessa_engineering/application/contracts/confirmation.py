"""Product-selected policy and exact approval storage ports; sole contract owner."""
from typing import Protocol
from ...domain.approvals.consent import (
    ConsentPolicyRef, ConversationNotice, AuthorizationIntent, ConsentChallenge,
    ConversationEvidence, CapturedInstructionEvidence, ApprovalGrant, NoticeRef,
)
from ...domain.approvals.refs import ApprovalRef


class ConversationAdmissionPort(Protocol):
    policy_ref: ConsentPolicyRef
    evidence_kinds: tuple[str, ...]
    def guard_capture(self, context, source, policy_ref): ...
    def guard_intent(self, context, intent: AuthorizationIntent): ...
    def guard_evidence(self, context, intent: AuthorizationIntent,
                       evidence: ConversationEvidence | CapturedInstructionEvidence): ...


class AuthorizationRepository(Protocol):
    def require_apply_schema(self) -> None: ...
    def require_implementation_authorization_schema(self) -> None: ...
    def put_notice(self, notice: ConversationNotice) -> None: ...
    def get_notice(self, ref: NoticeRef) -> ConversationNotice: ...
    def put_intent(self, intent: AuthorizationIntent) -> None: ...
    def get_intent(self, identifier: str) -> AuthorizationIntent: ...
    def put_challenge(self, challenge: ConsentChallenge) -> None: ...
    def get_challenge(self, identifier: str): ...
    def list_pending(self, *, limit: int, after_challenge_id: str | None): ...
    def transition_challenge(self, identifier: str, expected_version: int, state: str) -> None: ...
    def put_receipt(self, challenge: ConsentChallenge,
                    evidence: ConversationEvidence | CapturedInstructionEvidence) -> bool: ...
    def put_grant(self, grant: ApprovalGrant) -> None: ...
    def get_grant(self, ref: ApprovalRef) -> ApprovalGrant: ...
    def get_control(self, ref: ApprovalRef): ...
    def revoke(self, ref: ApprovalRef, expected_version: int, occurred_at: str, reason: str, event_id: str) -> None: ...
    def consume_action(self, ref: ApprovalRef, *, action: str, action_instance_id: str,
                       target_digest, now: str): ...
    def check_action_consumptions(self, ref: ApprovalRef, *, intent_digest, target_digest, action_instances): ...
    def action_budget(self, ref: ApprovalRef): ...
    def put_apply(self, receipt): ...
    def get_apply(self, apply_id: str): ...
