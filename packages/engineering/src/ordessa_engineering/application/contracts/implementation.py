"""Original UoW ports for repository content and frozen implementation packages."""
from typing import Protocol
from ...domain.changes.baselines import RepositorySnapshotRef
from ...domain.changes.repository_baseline import RepositoryBaseline
from ...domain.packages.models import ImplementationPackage
from ...domain.packages.refs import ImplementationPackageRef

class ImplementationRepository(Protocol):
    def create_repository_baseline(self, record: RepositoryBaseline) -> RepositorySnapshotRef: ...
    def resolve_repository_baseline(self, ref: RepositorySnapshotRef) -> RepositoryBaseline: ...
    def create_package(self, record: ImplementationPackage) -> ImplementationPackageRef: ...
    def resolve_package(self, ref: ImplementationPackageRef) -> ImplementationPackage: ...
    def read_blob(self, ref) -> bytes: ...
    def read_prepared_document(self, package_ref, role) -> bytes: ...
