"""Application repository ports (single owner per repository/access seam)."""
from ordessa_engineering.domain.reviews.models import ReviewRequestExpectation
from typing import Protocol

from ...domain.artifacts.models import Artifact, ArtifactRevision
from ...domain.artifacts.refs import (ArtifactRevisionRef)
from ...domain.common.models.refs import (BlobRef)
from ...domain.common.models.values import (Digest)
from ...domain.common.models.identity import (Scope)
from ...domain.changes.refs import (ProposalRef)
from ...domain.changes.models import Change, Proposal, ProposalControl, ChangeSet
from ...domain.reviews.refs import (ReviewRef)
from ...domain.reviews.models import (
    ReviewRequirement,
    ReviewPlan,
    ReviewRecord,
    ReviewRequestState,
    ReviewSetKey,
    ReviewSetSnapshot,
    ReviewSetExpectation,
    ReviewControlExpectation,
    ControlledReview,
)
from .commands import CommandContext, CommandKey, JournalEntry, ReadSet, Reservation

__all__ = ['ArtifactRepository', 'CommandJournal', 'ProposalRepository', 'ProposalControlAdmission',
           'ReviewRepository', 'CommandAccessPort', 'ProposalReadPort']


class ArtifactRepository(Protocol):
    def apply_head_plan(self, plan): ...
    def apply_acceptance_plan(self, plan): ...
    def require_material_schema(self) -> None: ...
    def create(self, artifact: Artifact) -> None: ...
    def get_artifact(self, artifact_id: str) -> Artifact: ...
    def append_revision(self, revision: ArtifactRevision, *, expected_version: int) -> ArtifactRevisionRef: ...
    def resolve_revision(self, ref: ArtifactRevisionRef) -> ArtifactRevision: ...
    def check_read_set(self, read_set: ReadSet) -> None: ...


class CommandJournal(Protocol):
    def reserve(self, key: CommandKey, *, project_id: str, operation: str,
                operation_id: str, request_digest: Digest) -> Reservation: ...
    def get(self, key: CommandKey) -> JournalEntry | None: ...
    def complete(self, key: CommandKey, *, expected_version: int, result_bytes: bytes,
                 state: str = "completed") -> JournalEntry: ...
    def find_completed_review_request(self, scope, *, review_id: str,
                                      plan_digest: Digest) -> JournalEntry | None: ...


class ProposalRepository(Protocol):
    def resolve_revision_graph(self, roots, budget): ...
    def create_change(self, change: Change) -> None: ...
    def get_change(self, change_id: str) -> Change: ...
    def validated_budget(self): ...
    def create_proposal(self, proposal: Proposal, *, expected_version: int, budget, requirements) -> ProposalRef: ...
    def get_proposal(self, ref: ProposalRef, *, budget=None) -> Proposal: ...
    def get_control(self, ref: ProposalRef, *, budget=None) -> ProposalControl: ...
    def select(self, ref: ProposalRef, *, expected_version: int) -> Change: ...
    def control(self, ref: ProposalRef, *, expected_version: int, disposition: str,
                replacement_ref: ProposalRef | None, evidence: tuple[Digest,...],
                at: str, actor, reason: str) -> ProposalControl: ...
    def validate_change_set(self, refs: tuple[ProposalRef,...]) -> ChangeSet: ...


class ProposalControlAdmission(Protocol):
    """Trusted owner guard, kept active through the same command commit.

    Yields verified action digests; a client evidence tuple never implements it.
    """
    def guard_control(self, context: CommandContext, proposal: Proposal,
        control: ProposalControl, disposition: str, replacement: Proposal | None): ...


class ReviewRepository(Protocol):
    def get_requirement(self, identifier: str, requirement_version: int) -> ReviewRequirement: ...
    def ensure_requirement(self, requirement: ReviewRequirement) -> ReviewSetKey: ...
    def create_plan(self, plan: ReviewPlan) -> ReviewRequestState: ...
    def get_plan(self, review_id: str) -> ReviewPlan: ...
    def get_request(self, review_id: str) -> ReviewRequestState: ...
    def withdraw_request(self, review_id: str, *, expected_version: int, fence: int) -> ReviewRequestState: ...
    def insert_review(self, record: ReviewRecord, *, expected_request_version: int, fence: int) -> ReviewRef: ...
    def get_review(self, ref: ReviewRef) -> ControlledReview: ...
    def read_set(self, key: ReviewSetKey) -> ReviewSetSnapshot: ...
    def check_expectations(self, sets: tuple[ReviewSetExpectation, ...] = (),
                           controls: tuple[ReviewControlExpectation, ...] = (),
                           requests: tuple[ReviewRequestExpectation, ...] = ()) -> None: ...
    def control_group(self, expectations: tuple[ReviewControlExpectation, ...], *, state: str,
                      reason: str, evidence: tuple[Digest, ...],
                      replacement_ref: ReviewRef | None = None) -> ReviewSetSnapshot: ...


class CommandAccessPort(Protocol):
    """Trusted composition supplies this port; a client ActorRef is not proof."""
    def require(self, context: CommandContext, operation: str) -> None: ...

    def handoff_effect_write(self, context: CommandContext, *, invocation_key: bytes,
                             action_instances, target_thread, expires_at: float):
        """One opaque token for the original dispatch byte cut, with no new grant."""
        ...

    def consume_effect_write(self, handoff, context: CommandContext, *,
                             invocation_key: bytes, action_instances):
        """Revalidate the original admission on its exact selected SDK Thread."""
        ...


class ProposalReadPort(Protocol):
    """Application-owned reads the proposal closure needs; implemented by the adapter."""

    def read_proposal(self, ref, budget): ...
    def resolve_repository_baseline(self, ref, budget): ...
    def resolve_revision_graph(self, roots, budget): ...
    def select_artifact(self, scope, artifact_id): ...
